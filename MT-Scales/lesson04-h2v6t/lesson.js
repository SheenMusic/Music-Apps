/* 调式与音阶 · 第四课：调式与旋律的变化（V2，2026-11-23）
   依据 docs/scales/lesson04-script.md。只讲音阶、调号与单旋律：不讲和弦、离调；转调只用主音中心清楚改变的例子。 */
(() => {
  'use strict';
  const {notes, melody, scale, toggle, cards, table, circle, lesson, C, DEGREES} = ScaleKit;
  const {section, say, note, q, TF, run} = lesson();
  const keyOnly = (key, caption = '') => notes([], {key, caption});
  const tune = (opts = {}) => melody('C4 E4 G4 E4 | A4 G4 D4 C4', {tonic: [0, 7], ...opts});
  const flat6 = (opts = {}) => melody('C4 E4 G4 E4 | Ab4 G4 D4 C4', {tonic: [0, 7], mark: [4], ...opts});

  section('intro', '导论', '调式与旋律的变化');
  say('一首乐曲可以保持某种音阶为主要参照，也可以在旋律中改变局部用音。', toggle([['原旋律', tune()], ['局部变音', flat6()]]));
  say('比较这些变化时，需要分别观察【主音是否改变】与【其他音级怎样改变】。', cards([['问题一', '主音是否改变？'], ['问题二', '其他音级怎样改变？']]));

  section('keys', '一', '关系大小调与平行大小调');
  say('关系大小调共用调号，其中的大调音阶与自然小调音阶共用完整音列。', toggle([
    ['C 大调', scale('C4', 'major', {caption: '主音 C'})], ['A 自然小调', scale('A3', 'natural', {caption: '主音 A：同一组音'})]
  ]));
  say('同一组音可以围绕不同主音组织，所以共用音列不等于音乐中心相同。', toggle([
    ['以 C 为落点', melody('C4 E4 G4 E4 | D4 B3 C4:h', {tonic: [0, 6], caption: '主音 C'})],
    ['以 A 为落点', melody('A3 C4 E4 C4 | B3 D4 A3:h', {tonic: [0, 6], caption: '主音 A'})]
  ]));
  say('主音相同的大调与小调，称为**平行大小调（Parallel Keys）**。', toggle([['C 大调', notes(C.major)], ['C 自然小调', notes(C.natural)]]));
  say('平行大小调的自然音阶在第三、第六、第七级上不同。', toggle([
    ['C 大调', notes(C.major, {mark: [2, 5, 6], labels: DEGREES.major})], ['C 自然小调', notes(C.natural, {mark: [2, 5, 6], labels: DEGREES.natural})]
  ], {pressed: 1}));
  say('常用调号范围内，平行大小调的调号沿五度循环相隔三个位置。', circle({hi: ['D', 'G', 'C', 'F'], caption: 'D 大调两个升号 → G → C → F 大调一个降号；D 小调与 F 大调同一个调号'}));
  note('部分中文教材把关系大小调称为「平行大小调」，本课程使用与英文 parallel 一致的同主音含义。', cards([
    ['关系大小调（relative）', 'C 大调与 A 小调：调号相同'], ['平行大小调（parallel）', 'C 大调与 C 小调：主音相同']]));
  q(cards(['D 大调']), 'D 大调的平行小调是哪个？', [['D 小调', true], ['B 小调'], ['F♯ 小调']],
    '正确。平行大小调主音相同，D 大调与 D 小调都是 D；B 小调则是关系小调。', '按本课程的用法，平行指主音相同还是调号相同？');
  q(toggle([['F 大调', scale('F4', 'major', {key: 'F', plain: true})], ['D 小调', scale('D4', 'natural', {key: 'Dm', plain: true})]]), 'F 大调与 D 小调是什么关系？',
    [['关系大小调', true], ['平行大小调']], '正确。两者调号相同、主音不同，是关系大小调。', '把主音相同与调号相同分开检查。');
  q(toggle([['D 大调', keyOnly('D')], ['D 小调', keyOnly('F')]]), 'D 大调与 D 小调的调号需要改变几个音名的默认升降状态？', [['三个', true], ['一个'], ['没有改变']],
    '正确。F♯、C♯ 恢复为自然音，B 变为 B♭，共三个音名发生变化。', '不要只用升降号个数相减，要检查实际改变了哪些音。');

  section('distance', '二', '调号的远近');
  say('在本课采用的常用大小调关系中，调号相同或只改变一个默认升降音的其他调，称为**近关系调（Closely Related Keys）**。',
    circle({showMinor: true, hi: ['C', 'a', 'G', 'e', 'F', 'd'], caption: 'C 大调：A 小调、G 大调、E 小调、F 大调、D 小调'}));
  say('一个调的五个近关系调，可以从本身及五度循环两侧相邻调号对应的大小调中找出。', table(['调号', '大调 / 小调'],
    [['一个降号', 'F 大调 / D 小调'], ['没有升降号', 'C 大调（本身）/ A 小调'], ['一个升号', 'G 大调 / E 小调']], {hi: [0, 2], title: '三组，除去 C 大调本身，共五个'}));
  say('近关系调的音阶有较多共同音，但共同音多不等于主音相同。', toggle([
    ['C 大调', scale('C4', 'major', {mark: [3]})], ['G 大调', scale('G4', 'major', {mark: [6], caption: '只有 F 与 F♯ 不同'})]
  ]));
  q(toggle([['E 大调', keyOnly('E')], ['E 小调', keyOnly('G')], ['D 小调', keyOnly('F')]]), '哪个不是 C 大调的近关系调？', [['E 大调', true], ['E 小调'], ['D 小调']],
    '正确。按本课定义，E 大调的调号与 C 大调相差不止一个升降音。', '比较调号，而不是只看两个主音离得近不近。');
  q(toggle([['C 大调', scale('C4', 'major', {plain: true})], ['G 大调', scale('G4', 'major', {plain: true})]]), '相邻调号的两条音阶共用很多音，就一定有同一个主音。', TF(false),
    '正确，这句话是错的。音列的相似程度与主音是谁，是两个不同问题。', '回想关系大小调，它们甚至共用完整自然音列。');

  section('mixture', '三', '旋律中的同主音借音');
  say('主音不变时，旋律可以局部使用同主音其他调式中的音，改变原有色彩。', toggle([['C 大调', tune()], ['A 改 A♭', flat6()]]));
  say('在原有调式语境中借用同主音其他调式的音，可以称为**调式交替（Modal Mixture）**。', flat6({tags: ['', '', '', '', '♭6'], caption: 'A♭：同主音自然小调中的 ♭6'}));
  say('大调旋律中的 ♭6，可以在主音保持不变的语境中解释为来自平行小调的用音。', toggle([
    ['原版', tune({mark: [4], caption: '第六级 A，结尾在 C'})], ['变体', flat6({caption: '第六级 A♭，结尾仍在 C（这是给定语境中的解释）'})]
  ], {pressed: 1}));
  say('局部借入一个音，不要求旋律的其他音也全部改成同主音小调。', flat6({mark: [1, 4], labels: ['1', '3', '5', '3', '♭6', '5', '2', '1'], caption: 'E 仍是 3，只有 A 改成 A♭'}));
  q(flat6({plain: true, caption: '已知：C 大调语境，主音 C'}), '已知 C 大调语境与 C 主音保持不变，A♭ 是相对主音的哪个音级？', [['♭6', true], ['♭3'], ['♯4']],
    '正确。C 大调第六级是 A，A♭ 低半音，写成 ♭6。', '以当前主音为 1，先找同主音大调中的相应音级。');
  q(melody('G4 B4 D5 B4 | Eb5 D5 A4 G4', {key: 'G', plain: true, caption: '主音 G'}), '保持 G 主音的大调旋律，局部借入 E♭，这个音可以在 G 自然小调中找到。', TF(true),
    '正确。E♭ 是 G 的 ♭6，也是 G 自然小调中的音。', '比较 G 大调与 G 自然小调的第六级。');
  say('借音的来源也可以是同主音的其他调式，不只限于大小调之间。', toggle([
    ['C 大调', melody('C4 E4 G4 B4 | A4 G4 D4 C4', {tonic: [0, 7], mark: [3]})],
    ['B 改 B♭', melody('C4 E4 G4 Bb4 | A4 G4 D4 C4', {tonic: [0, 7], mark: [3], caption: 'B♭ 也符合 C Mixolydian 的 ♭7'})]
  ], {pressed: 1}));
  say('同一个借入的音，可能同时属于多个同主音调式。', table(['C 为主音', '有没有 B♭（♭7）'],
    [['大调', '没有'], ['Mixolydian', '有'], ['Dorian', '有'], ['自然小调', '有'], ['Phrygian', '有']], {hi: [1, 2, 3, 4], title: '凭 B♭ 一个音，不能唯一认出来源'}));
  q(cards(['主音 D，旋律局部出现 C']), '主音保持 D，旋律局部出现 C，还能仅凭这个音唯一确定整段是 D Mixolydian 吗？', [['不能', true], ['能']],
    '正确。C 是 D 的 ♭7，但 D 自然小调、Dorian 等也有这个音，仍要检查其他用音。', '列出已经学过、同样包含 ♭7 的音阶。');
  note('一个临时变音可以有不同作用，不能只凭它就断定调式交替或主音改变。', notes(['Ab4'], {noTonic: true, mark: [0], caption: '只看到一个 A♭，前后旋律与主音都不知道：信息不足'}));
  q(notes(['Ab4'], {noTonic: true, plain: true}), '只看到一个 A♭、不知道前后旋律与主音，就能断定它是大调借用平行小调的 ♭6。', TF(false),
    '正确，这句话是错的。必须先知道主音，才能确定它是第几级，再结合旋律语境解释。', '离开主音信息，同一个音名是否只有一种音级身份？');

  section('modulation', '四', '移调与主音中心的改变');
  const inC = (opts = {}) => melody('C4 E4 G4 E4 | F4 D4 B3 C4', {tonic: [0, 7], ...opts});
  const inD = (opts = {}) => melody('D4 F#4 A4 F#4 | G4 E4 C#4 D4', {key: 'D', tonic: [0, 7], ...opts});
  const NUMS = ['1', '3', '5', '3', '4', '2', '7', '1'];
  say('把一段旋律的各音按同一音程整体移动，称为**移调（Transposition）**。', toggle([['C 大调', inC()], ['上移大二度', inD()]]));
  say('移调可以改变实际音高，而保持旋律的音级关系与音程结构。', toggle([['C 大调', inC({labels: NUMS})], ['D 大调', inD({labels: NUMS, caption: '7 在主音下方'})]], {pressed: 1}));
  // 完整的两段写在同一行时较小，另设「前段」「后段」按钮放大看
  const both = (opts = {}) => toggle([
    ['前段', inC()], ['后段', melody('D4 F#4 A4 F#4 | G4 E4 C#4 D4 | D4:w', {tonic: [0, 7, 8], mark: [0, 7, 8]})],
    ['完整', melody('C4 E4 G4 E4 | F4 D4 B3 C4 | D4 F#4 A4 F#4 | G4 E4 C#4 D4 | D4:w', {wide: 2.3, tonic: [0, 7], ...opts})]
  ], {pressed: 2});
  say('乐曲进行中确立一个新的调，称为**转调（Modulation）**。', both({mark: [8, 15, 16], caption: '先以 C 为中心，再在 D 上完整重现并停在 D。移调是整首换高度；转调发生在同一首曲子之内'}));
  say('旋律的反复、重音与完整乐句，也可以帮助新的主音中心建立起来。', both({mark: [8, 15, 16], tags: ['', '', '', '', '', '', '', '', 'D', '', '', '', '', '', '', 'D', 'D'], caption: '新段的首拍、句末与长音都落在 D，不靠单个变化音定调'}));
  say('本课先认识同一旋律换到新主音、并在新调中继续的清楚例子。', cards(['完整短曲由老师选定后再加入', '这里先用第 28 页的两句示意']));
  q(toggle([
    ['前段', melody('F4 A4 C5 A4 | Bb4 G4 E4 F4', {key: 'F', plain: true, caption: '主音 F'})],
    ['后段', melody('G4 B4 D5 B4 | C5 A4 F#4 G4', {key: 'G', plain: true, caption: '主音 G'})]
  ]), '先完整演奏以 F 为主音的大调旋律，再以 G 为新主音原样重现，后一段的音阶种类怎样变化？',
    [['仍是大调，主音改变', true], ['变成自然小调'], ['变成 Phrygian']], '正确。实际音高和主音变了，但相对于各自主音的音级关系仍相同。', '用新的主音重新标 1，不要继续沿用原来的主音计算。');
  say('相同的音列也可能围绕不同主音组织，因此变化音数量不能单独证明转调。', toggle([
    ['C Lydian', scale('C4', 'lydian', {caption: '中心 C'})], ['G 大调', notes(['G4', 'A4', 'B4', 'C5', 'D5', 'E5', 'F#5', 'G5'], {key: 'G', caption: '中心 G：同一组音 C D E F♯ G A B'})]
  ]));
  q(cards(['C 大调旋律中出现 F♯']), 'C 大调旋律出现 F♯，是否仅凭这个音就能断定已经转到 G 大调？', [['不能', true], ['能']],
    '正确。F♯ 也可能是 C 语境中的 ♯4，需要继续观察主音中心及其他用音。', '同一组音能否组成不同主音的调式？');
  say('调号的改变有助于读谱，但是否建立新的调仍要结合音乐本身。', cards([['调号', '读谱的线索'], ['主音与旋律组织', '判断的依据']]));
  q(cards(['谱例只有一个变化音，旋律怎样围绕主音组织尚不清楚']), '谱例只提供一个变化音，尚未说明旋律怎样围绕主音组织，最合适的分析是什么？',
    [['先保留候选，继续观察', true], ['变化音出现就一定转调'], ['没换调号就一定没转调']], '正确。现有信息不足以唯一确定主音中心是否改变。', '避免用一个记号代替对整段旋律的判断。');

  section('summary', '小结', '调式与旋律的变化');
  say('分析旋律中的变化时，先分清主音中心与音级色彩，再决定现有信息足以说明什么。', cards([
    ['关系 / 平行', '共用调号 / 主音相同'], ['同主音借音', '主音不变，局部改变音级'], ['移调', '整体换高度，音级关系不变'],
    ['转调', '旋律清楚地建立新的主音'], ['信息不足', '保留候选，继续观察']]));

  run(['B3', 'C4', 'C#4', 'D4', 'E4', 'F4', 'F#4', 'G4', 'Ab4', 'A4', 'Bb4', 'B4', 'C5', 'D5', 'Eb5', 'E5', 'F#5', 'G5']);
})();
