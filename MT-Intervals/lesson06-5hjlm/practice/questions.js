/* 第六课 · 结业测验：覆盖音程理论 1–6 课。每题的 module 对应一课，
   结果页与复制的报告按 modules 统计「一次通过率」，量化各单元的掌握程度。 */
(() => {
  const letters = ['A', 'B', 'C', 'D'];
  const TF = [{id: 'opt_true', label: '正确', value: '正确'}, {id: 'opt_false', label: '错误', value: '错误'}];
  const questions = [];
  const add = (module, q) => questions.push({id: `q${String(questions.length + 1).padStart(2, '0')}`, module, ...q,
    prompt: `${questions.length + 1}. ${q.prompt}`});
  const tf = (module, prompt, answer, explanation) => add(module, {type: 'boolean', prompt, options: TF, correctAnswer: [answer ? '正确' : '错误'], explanation});
  const choice = (module, prompt, labels, answer, explanation, notes) => add(module, {
    type: 'single-choice', prompt,
    options: labels.map((label, i) => ({id: `opt_${letters[i].toLowerCase()}`, label: `${letters[i]}. ${label}`, value: letters[i]})),
    correctAnswer: [answer], explanation, ...(notes ? {staff: {notes}} : {})
  });
  const ID = '判断谱例中的音程：';

  // 第 1 课：度数、旋律 / 和声音程、音数
  choice('L1', 'C–G（C 在下）的度数是：', ['四度', '五度', '六度', '七度'], 'B', 'C、D、E、F、G 共五个音级，所以是五度。');
  choice('L1', 'E–C（E 在下，C 在上）的度数是：', ['三度', '五度', '六度', '七度'], 'C', 'E、F、G、A、B、C 共六个音级，所以是六度。');
  choice('L1', 'C–E 的音数是：', ['1', '1½', '2', '2½'], 'C', 'C–D、D–E 都是全音，共 2 个全音，音数为 2。');
  tf('L1', '两个音同时发响构成的音程，叫做旋律音程。', false, '同时发响的是和声音程；先后发响的才是旋律音程。');

  // 第 2 课：音程的性质 / 自然音程
  choice('L2', '下列自然二度中，哪一个是小二度？', ['C–D', 'E–F', 'F–G', 'A–B'], 'B', '自然二度中只有 B–C、E–F 是小二度。');
  choice('L2', ID, ['大三度', '小三度', '纯四度', '减三度'], 'B', 'D–F 不在 C–E、F–A、G–B 之列，是小三度。', ['D4', 'F4']);
  choice('L2', ID, ['大三度', '小三度', '增三度', '大二度'], 'A', 'G–B 是自然大三度之一。', ['G4', 'B4']);
  tf('L2', '自然音程中，增四度只有 F–B 一个。', true, 'F–B 是自然音程中唯一的增四度，转位后是 B–F 减五度。');

  // 第 3 课：变化音程与等音程
  choice('L3', ID, ['纯四度', '增四度', '减五度', '增五度'], 'B', 'C–F 是纯四度；上方音升高，变宽一个半音，是增四度。', ['C4', 'F#4']);
  choice('L3', ID, ['纯五度', '减五度', '增四度', '纯四度'], 'B', 'E–B 是纯五度；上方音降低，变窄一个半音，是减五度。', ['E4', 'Bb4']);
  tf('L3', 'C–F♯ 与 C–G♭ 音响相同、写法不同，它们是等音程。', true, '增四度 C–F♯ 与减五度 C–G♭ 同为 6 个半音，是等音程。');
  choice('L3', ID, ['大六度', '增六度', '小七度', '减七度'], 'B', 'E–C 是小六度；下方音降低、上方音升高，各变宽一个半音，是增六度。', ['Eb4', 'C#5']);

  // 第 4 课：单音程与复音程
  choice('L4', '下列哪一个是复音程？', ['纯八度', '大九度', '大七度', '增八度'], 'B', '超过八度的音程是复音程；纯八度、增八度仍属单音程。');
  choice('L4', ID, ['大二度', '大九度', '小九度', '大十度'], 'B', 'C–D 是大二度，加一个八度是大九度。', ['C4', 'D5']);
  choice('L4', '纯十二度对应的单音程是：', ['纯四度', '纯五度', '纯六度', '大五度'], 'B', '12 − 7 = 5，性质不变，对应纯五度。');
  choice('L4', ID, ['小十度', '大十度', '小三度', '小九度'], 'A', 'E–G 是小三度，加一个八度是小十度。', ['E4', 'G5']);

  // 第 5 课：原位音程与转位音程
  choice('L5', '大六度转位后是：', ['小三度', '大三度', '小六度', '减三度'], 'A', '9 − 6 = 3；大变小，所以是小三度。');
  choice('L5', '增二度转位后是：', ['减七度', '增七度', '小七度', '减六度'], 'A', '9 − 2 = 7；增变减，所以是减七度。');
  tf('L5', '纯五度转位后是纯四度。', true, '9 − 5 = 4，纯音程转位后仍为纯音程。');
  choice('L5', '纯十一度转位成单音程是：', ['纯五度', '纯四度', '减五度', '纯六度'], 'A', '复音程转位成单音程，度数和为 16：16 − 11 = 5；纯音程不变。');

  // 第 6 课：快速识别（综合）
  choice('L6', ID, ['大三度', '小三度', '减三度', '增三度'], 'B', '二、三度找参照：F–A 是大三度，下方音升高变窄，是小三度。', ['F#4', 'A4']);
  choice('L6', ID, ['减五度', '纯五度', '增五度', '纯四度'], 'B', '四、五度看特例：B–F 是减五度，下方音降低变宽，是纯五度。', ['Bb4', 'F5']);
  choice('L6', ID, ['小六度', '大六度', '大七度', '增六度'], 'B', '六度先转位：B–D 是小三度，反转回来是大六度。', ['D4', 'B4']);
  choice('L6', ID, ['大七度', '小七度', '减七度', '小六度'], 'B', '七度先转位：D–E 是大二度，反转回来是小七度。', ['E4', 'D5']);
  choice('L6', ID, ['小七度', '大七度', '增七度', '减八度'], 'B', '七度先转位：F♯–G 是小二度，反转回来是大七度。', ['G4', 'F#5']);
  choice('L6', ID, ['纯四度', '纯十一度', '纯十二度', '增十一度'], 'B', '复音程减 7：D–G 是纯四度，所以是纯十一度。', ['D4', 'G5']);

  window.practiceData = {
    lessonId: 'music-theory-practice-06',
    lessonTitle: '音程理论 · 结业测验',
    questions,
    modules: [
      {id: 'L1', title: '第 1 课 · 度数与音数'},
      {id: 'L2', title: '第 2 课 · 性质与自然音程'},
      {id: 'L3', title: '第 3 课 · 变化音程与等音程'},
      {id: 'L4', title: '第 4 课 · 单音程与复音程'},
      {id: 'L5', title: '第 5 课 · 音程的转位'},
      {id: 'L6', title: '第 6 课 · 快速识别'}
    ],
    code: 'MT06',
    title: '结业测验',
    reportTitle: '音程理论结业测验',
    subtitle: '音程理论基础 · 第六课'
  };
})();
