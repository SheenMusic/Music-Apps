import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import os from 'node:os';
import {root,readConfig,studentDirectories,isStudentDirectoryName} from './student-config.mjs';
const marker='<!-- AUTO-GENERATED by scripts/generate-student-pages.mjs, do not edit. -->';
const template=fs.readFileSync(path.join(root,'students/shared/index.template.html'),'utf8');
function escapeHtml(value) {
  return value.replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
}
function expected(directory) {
  const file=path.join(directory,'student-data.js'), data=readConfig(file,'studentData');
  if (typeof data.studentName!=='string' || !data.studentName.trim()) throw new Error('studentName must be a non-empty string');
  const hash=crypto.createHash('sha1').update(fs.readFileSync(file)).digest('hex').slice(0,8);
  return template.replace('{{STUDENT_NAME}}',()=>escapeHtml(data.studentName)).replace('{{DATA_HASH}}',hash);
}
function randomDirectory() {
  while (true) {
    const directory=path.join(root,'students',crypto.randomBytes(16).toString('hex'));
    try {fs.mkdirSync(directory);return directory;}
    catch(error) {if(error.code!=='EEXIST') throw error;}
  }
}
try {
  const args=process.argv.slice(2);
  if (args[0]==='--new') {
    if(args.length!==2 || !args[1].trim()) throw new Error('Usage: --new "display name"');
    const directory=randomDirectory();
    const data={studentName:args[1],courses:[],learningPeriods:[]};
    fs.writeFileSync(path.join(directory,'student-data.js'),'const studentData = '+JSON.stringify(data,null,2)+';\n');
    fs.writeFileSync(path.join(directory,'index.html'),expected(directory));
    console.log('Created '+path.relative(root,directory)+'/');
  } else {
    if(args.length>1 || (args.length && !['--check','--migrate'].includes(args[0]))) throw new Error('Usage: [--check | --migrate | --new "display name"]');
    const check=args[0]==='--check',migrate=args[0]==='--migrate';
    const pages=studentDirectories().map(directory=>{
      if(!isStudentDirectoryName(path.basename(directory))) throw new Error('Student directories must use 32 hex characters');
      const file=path.join(directory,'index.html'), html=expected(directory), original=fs.existsSync(file)?fs.readFileSync(file,'utf8'):null;
      if (!check && original!==null && !original.includes(marker)) {
        if (!migrate) throw new Error('Refusing to overwrite unmarked page: '+path.relative(root,file));
        const originalStructure=html.replace(marker+'\n','').replace('  <meta name="referrer" content="no-referrer">\n','').replace(/student-data\.js\?v=[a-f0-9]{8}/,'student-data.js');
        if (original!==originalStructure) throw new Error('Unrecognized page structure; manual review required: '+path.relative(root,file));
      }
      return {file,html,original};
    });
    // Preflight every page before any write. Migration backups never enter the repository.
    let backup;
    if(migrate && pages.some(page=>page.original!==null && !page.original.includes(marker))) {
      backup=fs.mkdtempSync(path.join(os.tmpdir(),'student-page-migration-'));
      for(const page of pages) if(page.original!==null && !page.original.includes(marker)) fs.writeFileSync(path.join(backup,path.basename(path.dirname(page.file))+'.html'),page.original);
      console.log('Migration HTML backups: '+backup);
    }
    let differences=0;
    for(const page of pages) if(page.original!==page.html) {
      differences++;
      if(check) console.error('DIFFERENT '+path.relative(root,page.file));
      else {fs.writeFileSync(page.file,page.html);console.log('Generated '+path.relative(root,page.file));}
    }
    if(check && differences) process.exitCode=1;
    else console.log(`PASS ${pages.length} pages${check?' consistent':''}`);
  }
} catch(error) {console.error('ERROR '+error.message);process.exitCode=1;}
